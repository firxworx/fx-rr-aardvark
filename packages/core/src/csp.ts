/**
 * Content Security Policy (CSP) helpers.
 *
 * The policy is nonce-based: a fresh nonce is generated per request (worker entrypoint) and
 * passed to react-router's `<ServerRouter>`, `<Links>`, `<Scripts>`, `<ScrollRestoration>`
 * and any app-rendered inline `<script>` elements.
 *
 * Update the policy to support application requirements and to allow any third-party
 * resources (CDNs, fonts, analytics, image hosts, etc.) the app loads.
 *
 * Future considerations:
 *
 * - `require-trusted-types-for 'script'` to mitigate DOM XSS (requires additional client-side setup)
 * - reporting of violations via `report-to` directive + `Reporting-Endpoints` response header
 *
 * @see https://reactrouter.com/how-to/security#content-security-policy
 * @see https://base-ui.com/react/utils/csp-provider (base-ui may inject scripts/styles)
 * @see https://csp-evaluator.withgoogle.com/
 * @see https://developer.mozilla.org/en-US/docs/Web/HTTP/Reference/Headers/Content-Security-Policy
 *
 * @module
 */

import { invariant } from './helpers/invariant'

/**
 * CSP directives keyed by directive name (e.g. `script-src`) with a list of source values.
 * An empty list represents a directive with no value (e.g. `upgrade-insecure-requests`).
 */
export type CspDirectives = Record<string, string[]>

export interface ContentSecurityPolicyOptions {
  /** Per-request nonce value generated by `createCspNonce()`. */
  nonce: string

  /**
   * `true` for vite dev server builds to relax directives required by vite's client (HMR, error overlay).
   * Do not use to distinguish between Cloudflare environments (e.g. preview vs. production).
   */
  isDevelopment: boolean
}

const NONCE_BYTE_LENGTH = 16

/**
 * Generate a cryptographically random base64-encoded nonce value for use with CSP.
 *
 * Uses the Web Crypto API so it works across Cloudflare Workers, Node, and browsers.
 */
export function createCspNonce(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(NONCE_BYTE_LENGTH))
  return btoa(String.fromCharCode(...bytes))
}

/**
 * Create the app's CSP directives for the given per-request nonce.
 *
 * @throws {InvariantAssertionError} if `nonce` is empty
 */
export function createContentSecurityPolicy({ nonce, isDevelopment }: ContentSecurityPolicyOptions): CspDirectives {
  invariant(nonce.trim() !== '', 'CSP nonce must be a non-empty string')

  const nonceSource = `'nonce-${nonce}'`

  return {
    'default-src': ["'self'"],
    'script-src': ["'self'", nonceSource, "'strict-dynamic'"],

    // fallback for browsers without support for `style-src-elem` + `style-src-attr`
    'style-src': ["'self'", nonceSource],

    // omit nonce in development to support vite's injected styles (dev css + client error overlay)
    // remember 'unsafe-inline' is ignored if either a hash or nonce value is present in the source list
    'style-src-elem': isDevelopment ? ["'self'", "'unsafe-inline'"] : ["'self'", nonceSource],

    // support react libraries (e.g. base-ui) that set inline styles via the `style` attribute
    'style-src-attr': ["'unsafe-inline'"],

    'img-src': ["'self'", 'data:'],
    'font-src': ["'self'"],

    // allow websocket in development for vite hot module reloading (same-origin only for production)
    'connect-src': isDevelopment ? ["'self'", 'ws:'] : ["'self'"],

    // allow blob: in development to support the vite client error overlay
    'worker-src': isDevelopment ? ["'self'", 'blob:'] : ["'self'"],

    'object-src': ["'none'"],
    'base-uri': ["'none'"],
    'form-action': ["'self'"],
    'frame-ancestors': ["'none'"],

    // safety net (cloudflare is expected to enforce https upstream of workers)
    ...(isDevelopment ? undefined : { 'upgrade-insecure-requests': [] }),
  }
}

/**
 * Serialize CSP directives to a `Content-Security-Policy` header value.
 */
export function serializeContentSecurityPolicy(directives: CspDirectives): string {
  return Object.entries(directives)
    .map(([name, sources]) => (sources.length === 0 ? name : `${name} ${sources.join(' ')}`))
    .join('; ')
}
